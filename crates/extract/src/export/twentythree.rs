use std::io::{self, Write};

use super::layout::{Layout, Resolved, ascii_ordered};
use crate::{Site, SiteName, Timestamp};

pub(super) struct TwentyThree;

const HEADER_AFTER_TIMESTAMP: &str = "\r\n#\r\n# This file contains raw genotype data, including data that is not used in 23andMe reports.\r\n# This data has undergone a general quality review however only a subset of markers have been \r\n# individually validated for accuracy. As such, this data is suitable only for research, \r\n# educational, and informational use and not for medical or other use.\r\n# \r\n# Below is a text version of your data.  Fields are TAB-separated\r\n# Each line corresponds to a single SNP.  For each SNP, we provide its identifier \r\n# (an rsid or an internal id), its location on the reference human genome, and the \r\n# genotype call oriented with respect to the plus strand on the human reference sequence.\r\n# We are using reference human assembly build 37 (also known as Annotation Release 104).\r\n# Note that it is possible that data downloaded at different times may be different due to ongoing \r\n# improvements in our ability to call genotypes. More information about these changes can be found at:\r\n# https://you.23andme.com/tools/data/download/\r\n# \r\n# More information on reference human assembly builds:\r\n# https://www.ncbi.nlm.nih.gov/assembly/GCF_000001405.13/\r\n#\r\n# rsid\tchromosome\tposition\tgenotype\r\n";

impl Layout for TwentyThree {
	fn header(&self, sink: &mut impl Write, generated: Timestamp) -> io::Result<()> {
		write!(
			sink,
			"# This data file generated by 23andMe at: {}{HEADER_AFTER_TIMESTAMP}",
			generated.ctime()
		)
	}

	fn sort_key(&self, site: &Site) -> (u8, u32) {
		(
			u8::try_from(site.chrom().index()).unwrap_or(u8::MAX),
			site.grch37(),
		)
	}

	fn row(
		&self,
		sink: &mut impl Write,
		name: SiteName<'_>,
		site: &Site,
		genotype: Resolved,
	) -> io::Result<()> {
		write!(
			sink,
			"{name}\t{}\t{}\t",
			site.chrom().label(),
			site.grch37()
		)?;
		match genotype {
			Resolved::NoCall => sink.write_all(b"--")?,
			Resolved::One(allele) => sink.write_all(&[allele.ascii()])?,
			Resolved::Two(first, second) => sink.write_all(&ascii_ordered(first, second))?,
		}
		sink.write_all(b"\r\n")
	}
}
